#!/usr/bin/env python3
"""
Creates a smaller .webp twin next to every jpg/png under assets/ and rewrites js/webp-manifest.js.

Run this after you add or replace photos:      python tools/build-webp.py
Needs Pillow once:                              pip install pillow

The site keeps the original .jpg/.png (Supabase rows and old links still point at them); pages
automatically use the .webp twin for any image listed in js/webp-manifest.js.
"""
import os, glob, json, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SKIP = {'assets/images/qr-upi-payment.jpg'}      # payment QR must stay a byte-exact original
SKIP_DIRS = ('assets/icons/',)                    # PWA / notification icons stay PNG

made, tot_o, tot_n = [], 0, 0
files = [f for ext in ('jpg', 'jpeg', 'png') for f in glob.glob(f'assets/**/*.{ext}', recursive=True)]
for f in sorted(files):
    f = f.replace('\\', '/')
    if f in SKIP or f.startswith(SKIP_DIRS):
        continue
    out = os.path.splitext(f)[0] + '.webp'
    o = os.path.getsize(f)
    im = Image.open(f)
    if f.lower().endswith('.png'):
        im = im.convert('RGBA') if im.mode in ('RGBA', 'LA', 'P') else im.convert('RGB')
        im.save(out, 'WEBP', lossless=(o < 120 * 1024), quality=88, method=6)
    else:
        im.convert('RGB').save(out, 'WEBP', quality=80, method=6)
    n = os.path.getsize(out)
    if n >= o * 0.92:                              # not worth it — keep the original only
        os.remove(out)
        continue
    made.append(f); tot_o += o; tot_n += n

js = ('/* AUTO-GENERATED by tools/build-webp.py — lists every image that has a .webp twin next to it.\n'
      '   Utils.assetSrc / UI.link swap to the .webp automatically for those paths (when the browser supports WebP). */\n'
      'window.SMD_WEBP = new Set(' + json.dumps(made, separators=(',', ':')) + ');\n')
open('js/webp-manifest.js', 'w', encoding='utf-8').write(js)
print(f'{len(made)} images -> .webp  ({tot_o // 1024} KB -> {tot_n // 1024} KB). Manifest updated.')
